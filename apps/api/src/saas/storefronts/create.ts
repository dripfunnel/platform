// The create-storefront Workflow's steps (SAAS §5 steps 4–8, storefront LIVE-SHOP.md §3). Each is idempotent, moves the
// job to itself, and registers its compensation before it acts; a failure anywhere undoes them all, newest first.

export interface CreateDeps {
  sql: postgres.Sql
  github: GitHubApp
  org: string
  sites: SitesBucket
  /** SHOP_DOMAIN: names the shop a local `next dev` proxies to; null where none is set. */
  shopDomain: string | null
  now: () => Date
  /** Tests name a step to fail at the end of, to prove a failure there leaves nothing behind (SAAS §5). */
  failAt?: (step: ProvisioningStep) => void
}

export interface CreateParams {
  storeId: string
  jobId: string
  template: string
}

/** A Workflow's `step.do`: a step's answer is kept, so a replay skips what already finished. */
export interface StepRunner {
  do: (name: string, work: () => Promise<string>) => Promise<string>
}

export const createSteps = ['repo', 'storeConfig', 'hostingTarget', 'firstBuild', 'done'] as const satisfies readonly ProvisioningStep[]

// Read by the merchant and the partner (FIRST-RELEASE §7): plain words, never the cause.
export const createFailedMessage = 'We couldn’t set up the site. Nothing was kept, and it can be tried again.'

/** A step's answer when its job is no longer running (finished, undone, or the store changed): nothing to do or undo. */
const stopped = 'stopped'

class Stopped extends Error {
  override name = 'Stopped'
}

const hex = (buffer: ArrayBuffer) => [...new Uint8Array(buffer)].map((b) => b.toString(16).padStart(2, '0')).join('')

const enter = async (deps: CreateDeps, p: CreateParams, step: ProvisioningStep): Promise<(CreationRow & { repo: string }) | null> => {
  const row = await withSystemScope(deps.sql, async (tx) => {
    const found = await selectCreation(tx, p.storeId, p.jobId)
    if (found?.job_state === 'running') await moveJobTo(tx, p.jobId, step, deps.now())
    return found
  })
  if (!row?.repo || row.job_state !== 'running' || row.repo_state !== 'creating' || row.storefront_kind !== 'ai') return null
  return { ...row, repo: row.repo }
}

const pushed = (result: PushResult): string => {
  if (!result.ok) throw new Error(`create-storefront: push refused (${result.code})`)
  return result.commit
}

/** Step 4: the public repo, its Actions locked, then the skeleton, the theme and the locked workflow as one commit. */
const repoStep = async (deps: CreateDeps, p: CreateParams): Promise<string> => {
  const entered = await enter(deps, p, 'repo')
  if (!entered) return stopped
  const { repo } = entered
  const core = await currentCore(deps.sites)
  const { skeleton, theme } = await templateFiles(deps.sites, core, p.template)
  await withSystemScope(deps.sql, (tx) => appendCompensation(tx, p.jobId, { step: 'repo', undo: 'deleteRepo', repo }))
  const repos = storeRepos(deps.github.session(), deps.org)
  const created = await repos.create(repo)
  await repos.lockActions(repo)
  const first = await repos.head(repo)
  if (!first) throw new Error('create-storefront: the new repo has no main yet')
  await withSystemScope(deps.sql, async (tx) => {
    await setRepoId(tx, p.storeId, created.id)
    await setFirstRepoHead(tx, p.storeId, first)
  })
  pushed(
    await commitToMain({ sql: deps.sql, repos, now: deps.now }, p.storeId, `template:${p.jobId}`, `Start from the ${p.template} template`, ['creating'], async () => ({
      replace: true,
      changes: [...skeleton, ...theme],
    })),
  )
  deps.failAt?.('repo')
  return core
}

const storeConfigFile = (publicStoreKey: string) =>
  `// Generated by DripFunnel and locked (storefront ARCHITECTURE §2.2).\nexport const storeConfig = {\n  publicStoreKey: '${publicStoreKey}',\n  shopApi: '/shop-api',\n} as const\n`

const pinnedPackage = (skeletonPackage: string, repo: string, core: string): string => {
  const pkg = JSON.parse(skeletonPackage) as Record<string, unknown>
  const dependencies = typeof pkg['dependencies'] === 'object' && pkg['dependencies'] !== null ? pkg['dependencies'] : {}
  return `${JSON.stringify({ ...pkg, name: repo, dependencies: { ...dependencies, '@dripfunnel/storefront-core': core } }, null, 2)}\n`
}

// Read only by a clone's `next dev` (templates/storefront/next.config.ts): the store's own free address.
const devEnvFile = (slug: string, shopDomain: string) => `SHOP_API_PROXY=https://${slug}.${shopDomain}\n`

/** Step 5: `store.config.ts`, core pinned exactly, and the shop a local run proxies to (storefront ARCHITECTURE §2.2). */
const configStep = async (deps: CreateDeps, p: CreateParams, core: string): Promise<string> => {
  const row = await enter(deps, p, 'storeConfig')
  if (!row) return stopped
  const { skeleton } = await templateFiles(deps.sites, core, p.template)
  const skeletonPackage = skeleton.find((f) => f.path === 'package.json')?.content ?? '{}'
  const repos = storeRepos(deps.github.session(), deps.org)
  pushed(
    await commitToMain({ sql: deps.sql, repos, now: deps.now }, p.storeId, `config:${p.jobId}`, `Store settings and storefront-core ${core}`, ['creating'], async () => ({
      replace: false,
      changes: [
        { path: 'store.config.ts', content: storeConfigFile(row.public_store_key) },
        { path: 'package.json', content: pinnedPackage(skeletonPackage, row.repo, core) },
        ...(deps.shopDomain ? [{ path: '.env.development', content: devEnvFile(row.slug, deps.shopDomain) }] : []),
      ],
    })),
  )
  deps.failAt?.('storeConfig')
  return core
}

/** Step 6: nothing to create in R2 (LIVE-SHOP §1); the store's prefix is recorded as what to delete. */
const hostingStep = async (deps: CreateDeps, p: CreateParams): Promise<string> => {
  if (!(await enter(deps, p, 'hostingTarget'))) return stopped
  const prefix = storePrefix(p.storeId)
  await withSystemScope(deps.sql, (tx) => appendCompensation(tx, p.jobId, { step: 'hostingTarget', undo: 'deleteFolders', prefix }))
  deps.failAt?.('hostingTarget')
  return prefix
}

/** Step 7: the template's prebuilt preview copied into the store's first preview folder, each file confirmed by its hash. */
const previewStep = async (deps: CreateDeps, p: CreateParams, core: string): Promise<string> => {
  const row = await enter(deps, p, 'firstBuild')
  if (!row) return stopped
  const ref = p.jobId
  const folder = previewFolder(p.storeId, ref)
  await withSystemScope(deps.sql, (tx) => appendCompensation(tx, p.jobId, { step: 'firstBuild', undo: 'deletePreview', folder, ref }))
  const manifest = await previewManifest(deps.sites, core, p.template)
  for (const file of manifest) {
    const source = await deps.sites.get(previewSource(core, p.template, file.path))
    if (!source) throw new TemplateMissing(`the ${p.template} preview lacks ${file.path}`)
    const copied = await deps.sites.put(`${folder}${file.path}`, await source.arrayBuffer(), { sha256: file.sha256, ...(source.httpMetadata ? { httpMetadata: source.httpMetadata } : {}) })
    const written = copied?.checksums.sha256
    // SAAS §5 step 7: confirmed from the copy's result, never assumed.
    if (!written || hex(written) !== file.sha256) throw new Error(`create-storefront: ${file.path} wasn't copied whole`)
  }
  if (!row.repo_head) throw new Error('create-storefront: no head to start the draft from')
  const head = row.repo_head
  await withSystemScope(deps.sql, (tx) => upsertDesignDraft(tx, { storeId: p.storeId, headCommit: head, template: p.template, coreVersion: core, previewRef: ref, at: deps.now() }))
  deps.failAt?.('firstBuild')
  return ref
}

/** Step 8: one transaction records the repo as ready, its template and core, and ends the job. */
const doneStep = async (deps: CreateDeps, p: CreateParams, core: string): Promise<string> => {
  const row = await enter(deps, p, 'done')
  if (!row) return stopped
  await withSystemScope(deps.sql, async (tx) => {
    const at = deps.now()
    await finishStoreRepo(tx, { storeId: p.storeId, jobId: p.jobId, template: p.template, coreVersion: core, at })
    await activityLog.record(tx, {
      category: 'system',
      action: 'storefront.created',
      result: 'success',
      actorKind: 'job',
      actorId: 'create-storefront',
      actorLabel: 'Storefront setup',
      partnerId: row.partner_id,
      storeId: p.storeId,
      target: { type: 'storefront', id: p.storeId, label: row.repo },
      changes: [
        { field: 'template', before: null, after: p.template },
        { field: 'core_version', before: null, after: core },
      ],
      reason: null,
      api: 'system',
      requestId: null,
      ip: null,
      userAgent: null,
      visibility: 'partner',
    })
    deps.failAt?.('done')
  })
  return row.repo
}

/** How an undo ends: a failed run leaves the job failed with its cause for staff; an Admin Undo leaves it undone. */
type Ending = { by: 'failure'; step: ProvisioningStep; code: string } | { by: 'staff' }

/** Every registered compensation, newest first, then the store marked as able to try again. */
const undoStep = async (deps: CreateDeps, p: Pick<CreateParams, 'storeId' | 'jobId'>, ending: Ending): Promise<string> => {
  const row = await withSystemScope(deps.sql, async (tx) => {
    const found = await selectCreation(tx, p.storeId, p.jobId)
    if (found?.job_state === 'running') await setJobState(tx, p.jobId, 'cleaning')
    return found
  })
  if (row?.job_state !== 'running' && row?.job_state !== 'cleaning') return 'not running'
  const log = await withSystemScope(deps.sql, (tx) => selectCompensations(tx, p.jobId))
  for (const entry of [...log].reverse()) {
    switch (entry.undo) {
      case 'deletePreview':
        await deletePrefix(deps.sites, entry.folder)
        await withSystemScope(deps.sql, (tx) => deleteDesignDraft(tx, p.storeId, entry.ref))
        break
      case 'deleteFolders':
        await deletePrefix(deps.sites, entry.prefix)
        break
      case 'deleteRepo':
        await storeRepos(deps.github.session(), deps.org).remove(entry.repo)
        break
    }
  }
  if (ending.by === 'staff') {
    await withSystemScope(deps.sql, (tx) => undoStoreRepo(tx, { storeId: p.storeId, jobId: p.jobId, at: deps.now() }))
    return 'undone'
  }
  const failed = ending
  await withSystemScope(deps.sql, async (tx) => {
    // The cause for staff, as a code (core/log failureCode), never the error's words.
    await failStoreRepo(tx, { storeId: p.storeId, jobId: p.jobId, error: createFailedMessage, details: `Stopped at ${failed.step}: ${failed.code}`, at: deps.now() })
    await activityLog.record(tx, {
      category: 'system',
      action: 'storefront.create_failed',
      result: 'failed',
      actorKind: 'job',
      actorId: 'create-storefront',
      actorLabel: 'Storefront setup',
      partnerId: row.partner_id,
      storeId: p.storeId,
      target: { type: 'storefront', id: p.storeId, label: row.repo ?? 'storefront' },
      changes: [{ field: 'step', before: null, after: failed.step }],
      reason: null,
      api: 'system',
      requestId: null,
      ip: null,
      userAgent: null,
      visibility: 'partner',
    })
  })
  return 'undone'
}

/** SAAS §5 steps 4–8 in order; a step that fails for good undoes every step before it. */
export const runCreateStorefront = async (deps: CreateDeps, p: CreateParams, steps: StepRunner): Promise<'created' | 'undone' | 'stopped'> => {
  let at: ProvisioningStep = 'repo'
  const run = async (step: ProvisioningStep, work: () => Promise<string>) => {
    at = step
    const answer = await steps.do(step, work)
    if (answer === stopped) throw new Stopped()
    return answer
  }
  try {
    const core = await run('repo', () => repoStep(deps, p))
    await run('storeConfig', () => configStep(deps, p, core))
    await run('hostingTarget', () => hostingStep(deps, p))
    await run('firstBuild', () => previewStep(deps, p, core))
    await run('done', () => doneStep(deps, p, core))
    return 'created'
  } catch (error) {
    if (error instanceof Stopped) return 'stopped'
    const failed = { by: 'failure' as const, step: at, code: failureCode(error) }
    logEvent({ event: 'storefront_create_failed', api: 'system', storeId: p.storeId, code: `${failed.step}:${failed.code}` })
    await steps.do('undo', () => undoStep(deps, p, failed))
    return 'undone'
  }
}

/** An Admin Undo (#730): the compensations of a failed job, run in the Workflow after the request committed. */
export const runUndoStorefront = async (deps: CreateDeps, p: Pick<CreateParams, 'storeId' | 'jobId'>, steps: StepRunner): Promise<'undone' | 'not running'> => {
  const answer = await steps.do('undo', () => undoStep(deps, p, { by: 'staff' }))
  return answer === 'undone' ? 'undone' : 'not running'
}
